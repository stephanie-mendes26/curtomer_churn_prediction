-- QUERIE: DISTRIBUICAO DE CLIENTES
SELECT
    COUNT(*)                            AS total_clientes,
    COUNT(CASE WHEN STATUS = 'Ativo'   THEN 1 END) AS ativos,
    COUNT(CASE WHEN STATUS = 'Inativo' THEN 1 END) AS inativos,
    ROUND(100.0 * COUNT(CASE WHEN STATUS = 'Inativo' THEN 1 END) / COUNT(*), 2) AS pct_inativos
FROM CONTROLLER.dbo.PBI_Clientes;

-- QUERIE: DISTRIBUICAO DE INADIMPLENCIA POR STATUS 
SELECT
    STATUS,
    COUNT(*)                        AS total,
    AVG(DIASINADIMPLENTE)           AS media_dias_inadimplente,
    MAX(DIASINADIMPLENTE)           AS max_dias_inadimplente,
    COUNT(CASE WHEN DIASINADIMPLENTE > 0  THEN 1 END) AS possui_inadimplencia,
    COUNT(CASE WHEN DIASINADIMPLENTE > 30 THEN 1 END) AS inadimplente_30dias,
    COUNT(CASE WHEN DIASINADIMPLENTE > 60 THEN 1 END) AS inadimplente_60dias,
    COUNT(CASE WHEN DIASINADIMPLENTE > 90 THEN 1 END) AS inadimplente_90dias
FROM CONTROLLER.dbo.PBI_Clientes
GROUP BY STATUS;

-- QUERIE: PERFIL GEOGRAFICO DOS CLIENTES
SELECT
    UFENTREGA,
    STATUS,
    COUNT(*) AS total
FROM CONTROLLER.dbo.PBI_Clientes
GROUP BY UFENTREGA, STATUS
ORDER BY total DESC;

-- QUERIE: PRIMEIRA COMPRA

SELECT
    CLIENTE AS CODIGO,
    MIN(DATA_ENTRADA) AS primeira_compra
FROM CENTRAL.dbo.PBI_DESEMPENHO_MATERIAL
WHERE DATA_ENTRADA >= '2023-01-01'
GROUP BY CLIENTE;