-- QUERIE: CLIENTES DESDE 2023
SELECT COUNT(DISTINCT CLIENTE) AS clientes
FROM dbo.PBI_DESEMPENHO_MATERIAL
WHERE DATA_ENTRADA >= '2023-01-01';

-- QUERIE: DATA MIN MAX
SELECT
    MIN(DATA_ENTRADA) AS DATA_MIN,
    MAX(DATA_ENTRADA) AS DATA_MAX,
    COUNT(*) AS QTD
FROM dbo.PBI_DESEMPENHO_MATERIAL;

-- QUERIE:VOLUME POR ANO
SELECT
    YEAR(DATA_ENTRADA) AS ANO,
    COUNT(*) AS QTD
FROM dbo.PBI_DESEMPENHO_MATERIAL
GROUP BY YEAR(DATA_ENTRADA)
ORDER BY ANO;